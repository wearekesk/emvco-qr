use std::collections::HashSet;
use std::fmt;
use std::ops::Deref;

use crate::{
    crc::crc_hex,
    profiles::{GenericProfile, MpmProfile},
    tlv::{encode_all, Tlv},
    Error, Result,
};

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MpmPayload(pub String);

impl Deref for MpmPayload {
    type Target = str;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl AsRef<str> for MpmPayload {
    fn as_ref(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for MpmPayload {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

impl MpmPayload {
    pub fn into_inner(self) -> String {
        self.0
    }
}

#[derive(Clone, Debug)]
pub struct MpmBuilder<P = GenericProfile> {
    profile: P,
    objects: Vec<Tlv>,
}

impl Default for MpmBuilder<GenericProfile> {
    fn default() -> Self {
        Self::new()
    }
}

impl MpmBuilder<GenericProfile> {
    pub fn new() -> Self {
        Self::with_profile(GenericProfile)
    }
}

impl<P: MpmProfile> MpmBuilder<P> {
    pub fn with_profile(profile: P) -> Self {
        Self {
            profile,
            objects: Vec::new(),
        }
    }

    pub fn field(mut self, tag: &str, value: &str) -> Result<Self> {
        if tag == "63" {
            return Err(Error::InvalidPayload(
                "CRC tag 63 is generated by finish()".into(),
            ));
        }
        if self.objects.iter().any(|o| o.tag == tag) {
            return Err(Error::DuplicateTag(tag.to_owned()));
        }
        self.objects.push(Tlv::new(tag, value)?);
        Ok(self)
    }

    /// Adds a template value built from nested TLV objects.
    /// The profile validator remains responsible for whether this template/tag
    /// and its children are allowed by the chosen payment scheme.
    pub fn template(self, tag: &str, children: &[Tlv]) -> Result<Self> {
        let value = encode_all(children);
        self.field(tag, &value)
    }

    pub fn finish(self) -> Result<MpmPayload> {
        if !self
            .objects
            .iter()
            .any(|o| o.tag == "00" && o.value == "01")
        {
            return Err(Error::MissingTag(
                "00 (Payload Format Indicator = 01)".into(),
            ));
        }

        self.profile.validate_fields(&self.objects)?;
        let mut fields = self.objects;
        fields.extend(self.profile.merchant_account_info()?);

        let mut seen = HashSet::new();
        for field in &fields {
            if !seen.insert(field.tag.as_str()) {
                return Err(Error::DuplicateTag(field.tag.clone()));
            }
        }

        let mut body = encode_all(&fields);
        body.push_str("6304");
        let checksum = crc_hex(body.as_bytes());
        body.push_str(&checksum);

        if body.chars().count() > super::MAX_PAYLOAD_CHARS {
            return Err(Error::InvalidPayload(format!(
                "payload exceeds {} characters",
                super::MAX_PAYLOAD_CHARS
            )));
        }
        Ok(MpmPayload(body))
    }
}
